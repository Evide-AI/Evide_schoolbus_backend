-- School Bus Tracking — V1 Schema
-- Run this in the Supabase SQL editor (Dashboard -> SQL Editor -> New query).
-- Multi-tenant via school_id on every table; Row-Level Security added at the end.

create extension if not exists "uuid-ossp";

-- ============================================================
-- Core tenancy
-- ============================================================

create table schools (
  id uuid primary key default uuid_generate_v4(),
  name text not null,
  address text,
  latitude double precision,
  longitude double precision,
  created_at timestamptz not null default now()
);

-- ============================================================
-- Vehicles
-- ============================================================

create table buses (
  id uuid primary key default uuid_generate_v4(),
  school_id uuid not null references schools(id) on delete cascade,
  bus_number text not null,           -- e.g. "Bus 7" or a registration number
  gt06_device_imei text unique,       -- IMEI reported by the GT06 device's login packet
  seat_capacity int not null default 40,
  status text not null default 'not_running' check (status in ('running', 'not_running', 'maintenance')),
  is_active boolean not null default true,   -- false = retired/replaced bus
  replaced_by_bus_id uuid references buses(id),
  created_at timestamptz not null default now()
);

create index idx_buses_school on buses(school_id);
create index idx_buses_imei on buses(gt06_device_imei);

create table drivers (
  id uuid primary key default uuid_generate_v4(),
  school_id uuid not null references schools(id) on delete cascade,
  name text not null,
  phone text,
  role text not null check (role in ('driver', 'conductor')),
  bus_id uuid references buses(id),
  auth_user_id uuid,  -- links to Supabase Auth user once they log in
  created_at timestamptz not null default now()
);

create index idx_drivers_bus on drivers(bus_id);

-- ============================================================
-- Students & parents
-- ============================================================

create table students (
  id uuid primary key default uuid_generate_v4(),
  school_id uuid not null references schools(id) on delete cascade,
  admission_number text not null,
  full_name text not null,
  bus_id uuid references buses(id),
  pickup_lat double precision,
  pickup_lng double precision,
  drop_lat double precision,
  drop_lng double precision,
  photo_path text,
  created_at timestamptz not null default now(),
  unique (school_id, admission_number)
);

create index idx_students_bus on students(bus_id);

-- One parent login can be linked to multiple students (siblings)
create table parent_users (
  id uuid primary key default uuid_generate_v4(),
  auth_user_id uuid not null,  -- Supabase Auth user id
  phone text,                  -- for OTP delivery
  created_at timestamptz not null default now()
);

create table parent_student_links (
  parent_user_id uuid not null references parent_users(id) on delete cascade,
  student_id uuid not null references students(id) on delete cascade,
  primary key (parent_user_id, student_id)
);

-- Enforces your "max 3 concurrent trusted devices" rule per parent login
create table trusted_devices (
  id uuid primary key default uuid_generate_v4(),
  parent_user_id uuid not null references parent_users(id) on delete cascade,
  device_id text not null,          -- a stable installation id generated by the Flutter app
  device_label text,                -- e.g. "Redmi Note 12" for the parent to recognize it
  trusted_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique (parent_user_id, device_id)
);

create index idx_trusted_devices_parent on trusted_devices(parent_user_id);

-- ============================================================
-- Management users (role-based, not shared credentials)
-- ============================================================

create table management_users (
  id uuid primary key default uuid_generate_v4(),
  school_id uuid not null references schools(id) on delete cascade,
  auth_user_id uuid not null,
  full_name text not null,
  role text not null check (role in ('principal', 'transport_incharge', 'staff')),
  created_at timestamptz not null default now()
);

create index idx_management_school on management_users(school_id);

-- ============================================================
-- Routes & live/history position
-- ============================================================

create table routes (
  id uuid primary key default uuid_generate_v4(),
  bus_id uuid not null references buses(id) on delete cascade,
  route_type text not null default 'pickup' check (route_type in ('pickup', 'drop')),
  stop_sequence jsonb not null,     -- ordered array of {student_id, lat, lng}
  polyline text,                    -- road-snapped path from the Directions API
  distance_meters double precision,
  duration_seconds double precision,
  generated_at timestamptz not null default now(),
  unique (bus_id, route_type)
);

create index idx_routes_bus on routes(bus_id);

-- Latest known position per bus (upserted on every GT06 ping)
create table bus_live_position (
  bus_id uuid primary key references buses(id) on delete cascade,
  latitude double precision not null,
  longitude double precision not null,
  speed_kmh double precision,
  heading double precision,
  recorded_at timestamptz not null
);

-- Position history — purged after 7 days by a scheduled job
create table bus_position_history (
  id bigserial primary key,
  bus_id uuid not null references buses(id) on delete cascade,
  latitude double precision not null,
  longitude double precision not null,
  speed_kmh double precision,
  heading double precision,
  recorded_at timestamptz not null
);

create index idx_position_history_bus_time on bus_position_history(bus_id, recorded_at);

-- ============================================================
-- Trip state (auto-detected or manually triggered)
-- ============================================================

create table trip_state (
  bus_id uuid primary key references buses(id) on delete cascade,
  status text not null default 'NOT_STARTED' check (status in ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED')),
  started_at timestamptz,
  ended_at timestamptz,
  triggered_by text,  -- 'driver', 'conductor', or 'auto'
  updated_at timestamptz not null default now()
);

-- ============================================================
-- Notifications
-- ============================================================

create table notifications (
  id uuid primary key default uuid_generate_v4(),
  school_id uuid not null references schools(id) on delete cascade,
  bus_id uuid references buses(id),          -- null = whole-school notification
  sender_type text not null check (sender_type in ('management', 'driver', 'conductor', 'system')),
  sender_id uuid,
  title text not null,
  body text not null,
  category text,  -- 'BUS_STARTED', 'BUS_REACHED', 'ANNOUNCEMENT', 'SOS', 'BUS_NOT_RUNNING', etc.
  created_at timestamptz not null default now()
);

create index idx_notifications_school on notifications(school_id);
create index idx_notifications_bus on notifications(bus_id);

-- ============================================================
-- Temporary pickup/drop location changes
-- ============================================================

create table temp_location_requests (
  id uuid primary key default uuid_generate_v4(),
  student_id uuid not null references students(id) on delete cascade,
  requested_lat double precision not null,
  requested_lng double precision not null,
  requested_bus_id uuid references buses(id),   -- candidate bus, filled in by backend/management
  start_date date not null,
  end_date date not null,
  status text not null default 'PENDING' check (status in ('PENDING', 'APPROVED', 'REJECTED', 'EXPIRED')),
  is_saved_secondary_location boolean not null default false,
  requested_at timestamptz not null default now(),
  decided_at timestamptz,
  decided_by uuid references management_users(id)
);

create index idx_temp_location_student on temp_location_requests(student_id);

-- ============================================================
-- Attendance (marked by driver/conductor in their app)
-- ============================================================

create table attendance (
  id uuid primary key default uuid_generate_v4(),
  student_id uuid not null references students(id) on delete cascade,
  bus_id uuid not null references buses(id) on delete cascade,
  date date not null,
  present boolean not null default false,
  marked_by uuid references drivers(id),
  marked_at timestamptz not null default now(),
  unique (student_id, date)
);

create index idx_attendance_bus_date on attendance(bus_id, date);
create index idx_attendance_student_date on attendance(student_id, date);

-- ============================================================
-- FCM device tokens (push notifications to parents)
-- ============================================================

create table device_tokens (
  id uuid primary key default uuid_generate_v4(),
  parent_user_id uuid not null references parent_users(id) on delete cascade,
  fcm_token text not null unique,
  platform text,
  updated_at timestamptz not null default now()
);

create index idx_device_tokens_parent on device_tokens(parent_user_id);

-- ============================================================
-- Audit log for management actions
-- ============================================================

create table audit_log (
  id bigserial primary key,
  school_id uuid not null references schools(id) on delete cascade,
  management_user_id uuid references management_users(id),
  action text not null,       -- e.g. 'BUS_REPLACED', 'STUDENT_ADDED', 'TEMP_LOCATION_APPROVED'
  details jsonb,
  created_at timestamptz not null default now()
);

-- ============================================================
-- Row-Level Security
-- ============================================================
-- Enabled on every table, which is what clears the Supabase Studio warning
-- and is the actually-correct default: RLS + zero policies = locked to the
-- service_role key only (your Node.js backend), until a policy explicitly
-- opens a table up.
--
-- Tables the Flutter/React apps read directly via the Supabase client get a
-- SELECT policy below, scoped to what that user should see. Tables that
-- should stay backend-only (drivers, bus_position_history, trip_state,
-- audit_log) are enabled with no policy at all — the Node backend still
-- reaches them fine via service_role, which bypasses RLS entirely.
--
-- One RLS gotcha worth knowing: a policy that subqueries another table (e.g.
-- "parent sees students linked via parent_student_links") only works if the
-- querying role can also read the rows touched by that subquery — so
-- parent_users and parent_student_links need their own SELECT policies too,
-- even though no app screen queries them directly.

alter table schools enable row level security;
alter table buses enable row level security;
alter table drivers enable row level security;
alter table students enable row level security;
alter table parent_users enable row level security;
alter table parent_student_links enable row level security;
alter table trusted_devices enable row level security;
alter table management_users enable row level security;
alter table routes enable row level security;
alter table bus_live_position enable row level security;
alter table bus_position_history enable row level security;
alter table trip_state enable row level security;
alter table notifications enable row level security;
alter table temp_location_requests enable row level security;
alter table audit_log enable row level security;
alter table attendance enable row level security;
alter table device_tokens enable row level security;

-- --- Self-lookups (needed so the subqueries below can resolve under RLS) ---

create policy parent_sees_own_row on parent_users
  for select using (auth_user_id = auth.uid());

create policy parent_sees_own_links on parent_student_links
  for select using (
    parent_user_id in (select id from parent_users where auth_user_id = auth.uid())
  );

create policy management_sees_own_row on management_users
  for select using (auth_user_id = auth.uid());

-- --- Schools: low-sensitivity (name/location only) — any signed-in user ---

create policy authenticated_can_read_schools on schools
  for select using (auth.role() = 'authenticated');

-- --- Students ---

create policy parent_sees_own_students on students
  for select using (
    id in (
      select student_id from parent_student_links psl
      join parent_users pu on pu.id = psl.parent_user_id
      where pu.auth_user_id = auth.uid()
    )
  );

create policy management_sees_school_students on students
  for select using (
    school_id in (select school_id from management_users where auth_user_id = auth.uid())
  );

-- --- Buses ---

create policy parent_sees_linked_buses on buses
  for select using (
    id in (
      select s.bus_id from students s
      join parent_student_links psl on psl.student_id = s.id
      join parent_users pu on pu.id = psl.parent_user_id
      where pu.auth_user_id = auth.uid()
    )
  );

create policy management_sees_school_buses on buses
  for select using (
    school_id in (select school_id from management_users where auth_user_id = auth.uid())
  );

-- --- Routes ---

create policy parent_sees_linked_routes on routes
  for select using (
    bus_id in (
      select s.bus_id from students s
      join parent_student_links psl on psl.student_id = s.id
      join parent_users pu on pu.id = psl.parent_user_id
      where pu.auth_user_id = auth.uid()
    )
  );

create policy management_sees_school_routes on routes
  for select using (
    bus_id in (
      select id from buses
      where school_id in (select school_id from management_users where auth_user_id = auth.uid())
    )
  );

-- --- Live bus position (scoped, not "any authenticated user sees every bus") ---

create policy parent_sees_linked_bus_position on bus_live_position
  for select using (
    bus_id in (
      select s.bus_id from students s
      join parent_student_links psl on psl.student_id = s.id
      join parent_users pu on pu.id = psl.parent_user_id
      where pu.auth_user_id = auth.uid()
    )
  );

create policy management_sees_school_bus_position on bus_live_position
  for select using (
    bus_id in (
      select id from buses
      where school_id in (select school_id from management_users where auth_user_id = auth.uid())
    )
  );

-- --- Notifications ---

create policy parent_sees_relevant_notifications on notifications
  for select using (
    school_id in (
      select st.school_id from students st
      join parent_student_links psl on psl.student_id = st.id
      join parent_users pu on pu.id = psl.parent_user_id
      where pu.auth_user_id = auth.uid()
    )
    and (
      bus_id is null
      or bus_id in (
        select s.bus_id from students s
        join parent_student_links psl2 on psl2.student_id = s.id
        join parent_users pu2 on pu2.id = psl2.parent_user_id
        where pu2.auth_user_id = auth.uid()
      )
    )
  );

create policy management_sees_school_notifications on notifications
  for select using (
    school_id in (select school_id from management_users where auth_user_id = auth.uid())
  );

-- --- Trusted devices: parent manages their own (read/insert/delete) ---

create policy parent_manages_own_devices on trusted_devices
  for all using (
    parent_user_id in (select id from parent_users where auth_user_id = auth.uid())
  )
  with check (
    parent_user_id in (select id from parent_users where auth_user_id = auth.uid())
  );

-- --- Temp location requests: parent creates/views their own; management views their school's ---

create policy parent_manages_own_temp_requests on temp_location_requests
  for all using (
    student_id in (
      select student_id from parent_student_links psl
      join parent_users pu on pu.id = psl.parent_user_id
      where pu.auth_user_id = auth.uid()
    )
  )
  with check (
    student_id in (
      select student_id from parent_student_links psl
      join parent_users pu on pu.id = psl.parent_user_id
      where pu.auth_user_id = auth.uid()
    )
  );

create policy management_sees_school_temp_requests on temp_location_requests
  for select using (
    student_id in (
      select id from students
      where school_id in (select school_id from management_users where auth_user_id = auth.uid())
    )
  );

-- --- Driver self-lookup: a driver reads their own row (to find their bus) ---

create policy driver_sees_own_row on drivers
  for select using (auth_user_id = auth.uid());

-- --- Driver sees students on their assigned bus (for the attendance list) ---

create policy driver_sees_own_bus_students on students
  for select using (
    bus_id in (select bus_id from drivers where auth_user_id = auth.uid())
  );

-- --- Attendance: driver reads + writes their own bus's attendance;
--     management reads their school's attendance ---

create policy driver_reads_own_bus_attendance on attendance
  for select using (
    bus_id in (select bus_id from drivers where auth_user_id = auth.uid())
  );

create policy driver_writes_own_bus_attendance on attendance
  for insert with check (
    bus_id in (select bus_id from drivers where auth_user_id = auth.uid())
  );

create policy driver_updates_own_bus_attendance on attendance
  for update using (
    bus_id in (select bus_id from drivers where auth_user_id = auth.uid())
  );

create policy management_reads_school_attendance on attendance
  for select using (
    bus_id in (
      select id from buses
      where school_id in (select school_id from management_users where auth_user_id = auth.uid())
    )
  );

-- --- Management write access (INSERT / UPDATE / DELETE), scoped to own school ---

create policy management_inserts_school_buses on buses
  for insert with check (
    school_id in (select school_id from management_users where auth_user_id = auth.uid()));
create policy management_updates_school_buses on buses
  for update using (
    school_id in (select school_id from management_users where auth_user_id = auth.uid()))
  with check (
    school_id in (select school_id from management_users where auth_user_id = auth.uid()));
create policy management_deletes_school_buses on buses
  for delete using (
    school_id in (select school_id from management_users where auth_user_id = auth.uid()));

create policy management_inserts_school_students on students
  for insert with check (
    school_id in (select school_id from management_users where auth_user_id = auth.uid()));
create policy management_updates_school_students on students
  for update using (
    school_id in (select school_id from management_users where auth_user_id = auth.uid()))
  with check (
    school_id in (select school_id from management_users where auth_user_id = auth.uid()));
create policy management_deletes_school_students on students
  for delete using (
    school_id in (select school_id from management_users where auth_user_id = auth.uid()));

create policy management_inserts_school_notifications on notifications
  for insert with check (
    school_id in (select school_id from management_users where auth_user_id = auth.uid()));

create policy driver_inserts_own_bus_notifications on notifications
  for insert with check (
    bus_id in (select bus_id from drivers where auth_user_id = auth.uid())
    and school_id in (select school_id from drivers where auth_user_id = auth.uid()));

create policy parent_manages_own_tokens on device_tokens
  for all using (
    parent_user_id in (select id from parent_users where auth_user_id = auth.uid()))
  with check (
    parent_user_id in (select id from parent_users where auth_user_id = auth.uid()));

